$SecretsDir = Join-Path $Root "secrets"
$StateFile = Join-Path $SecretsDir "azure-lidr-deploy.state.env"

function Read-DotEnvFile {
    param([string]$Path)
    $map = @{}
    if (-not (Test-Path $Path)) { return $map }
    Get-Content $Path -Encoding UTF8 | ForEach-Object {
        $line = $_.Trim()
        if ($line -eq "" -or $line.StartsWith("#")) { return }
        $idx = $line.IndexOf("=")
        if ($idx -lt 1) { return }
        $k = $line.Substring(0, $idx).Trim()
        $v = $line.Substring($idx + 1).Trim()
        if ($v.StartsWith('"') -and $v.EndsWith('"')) { $v = $v.Substring(1, $v.Length - 2) }
        $map[$k] = $v
    }
    return $map
}

function Merge-EnvMaps {
    param([hashtable[]]$Maps)
    $out = @{}
    foreach ($m in $Maps) {
        foreach ($k in $m.Keys) { $out[$k] = $m[$k] }
    }
    return $out
}

function New-SqlPassword {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $b64 = [Convert]::ToBase64String($bytes) -replace '\+', 'A' -replace '/', 'B'
    return ("Lr9!" + $b64.Substring(0, 20))
}

function Test-AzCommand {
    param([scriptblock]$Block)
    $prev = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        & $Block 2>$null | Out-Null
        return ($LASTEXITCODE -eq 0)
    } finally {
        $ErrorActionPreference = $prev
    }
}

function Sync-BuildContext {
    $Dest = Join-Path $env:TEMP "legalrent-azure-build"
    Write-Host "Syncing project to $Dest ..."
    if (Test-Path $Dest) { Remove-Item -Recurse -Force $Dest }
    New-Item -ItemType Directory -Path $Dest -Force | Out-Null
    $robocopyArgs = @(
        $Root, $Dest, "/MIR",
        "/XD", "node_modules", "venv", ".venv", ".git", "backend\storage", "frontend\node_modules", "frontend\dist", "evals\runs", "secrets",
        "/XF", "*.pyc",
        "/NFL", "/NDL", "/NJH", "/NJS", "/nc", "/np"
    )
    & robocopy @robocopyArgs | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed with exit code $LASTEXITCODE" }
    return $Dest
}

Write-Host "Checking Azure login..."
$account = az account show -o json | ConvertFrom-Json
Write-Host "Subscription: $($account.name)"

if (-not (Test-AzCommand { az group show -n $RG -o none })) {
    Write-Host "Creating resource group $RG in $LOC ..."
    az group create -n $RG -l $LOC -o none
}

if (-not (Test-Path $SecretsDir)) { New-Item -ItemType Directory -Path $SecretsDir | Out-Null }

$state = Read-DotEnvFile $StateFile
$sqlPassword = $state["AZURE_SQL_ADMIN_PASSWORD"]
