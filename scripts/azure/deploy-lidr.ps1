$RG = "lidr"
$LOC = "eastus2"
# Azure SQL cannot be provisioned in eastus2 on this subscription; use centralus (same RG).
$SQL_LOC = "centralus"
$ACR = "legalrentlidracr"
$SQL_SERVER = "legalrentlidr-sql"
$SQL_DB = "LegalRentAI"
$SQL_ADMIN = "legalrentadmin"
