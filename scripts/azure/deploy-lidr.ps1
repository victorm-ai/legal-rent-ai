    @(
        "# Generated by scripts/azure/deploy-lidr.ps1 - do not commit",
        "AZURE_SQL_ADMIN_PASSWORD=$sqlPassword"
    ) | Set-Content -Path $StateFile -Encoding UTF8
    Write-Host "Saved SQL admin password to secrets/azure-lidr-deploy.state.env"
}

Write-Host "Ensuring ACR $ACR ..."
if (-not (Test-AzCommand { az acr show -n $ACR -g $RG -o none })) {
    az acr create -g $RG -n $ACR -l $LOC --sku Basic -o none
}
az acr update -n $ACR --admin-enabled true -o none | Out-Null

Write-Host "Ensuring SQL server $SQL_SERVER ..."
if (-not (Test-AzCommand { az sql server show -g $RG -n $SQL_SERVER -o none })) {
    az sql server create -g $RG -n $SQL_SERVER -l $SQL_LOC -u $SQL_ADMIN -p $sqlPassword -o none
}
if (-not (Test-AzCommand { az sql server firewall-rule show -g $RG -s $SQL_SERVER -n AllowAzureServices -o none })) {
    az sql server firewall-rule create -g $RG -s $SQL_SERVER -n AllowAzureServices `
        --start-ip-address 0.0.0.0 --end-ip-address 0.0.0.0 -o none
}

$myIp = (Invoke-RestMethod -Uri "https://api.ipify.org?format=json").ip
$clientRule = "Client_$($myIp -replace '\.', '_')"
if (-not (Test-AzCommand { az sql server firewall-rule show -g $RG -s $SQL_SERVER -n $clientRule -o none })) {
    az sql server firewall-rule create -g $RG -s $SQL_SERVER -n $clientRule `
        --start-ip-address $myIp --end-ip-address $myIp -o none
}

if (-not (Test-AzCommand { az sql db show -g $RG -s $SQL_SERVER -n $SQL_DB -o none })) {
    az sql db create -g $RG -s $SQL_SERVER -n $SQL_DB --service-objective S0 -o none
}

$acrLogin = az acr credential show -n $ACR -g $RG -o json | ConvertFrom-Json
$acrUser = $acrLogin.username
$acrPass = $acrLogin.passwords[0].value
$acrLoginServer = "$ACR.azurecr.io"

if (-not $SkipBuild) {
    $ctx = Sync-BuildContext
    Write-Host "Building API image in ACR (several minutes) ..."
    az acr build -r $ACR -g $RG -t "legalrent-api:$IMAGE_TAG" -f docker/backend/Dockerfile $ctx -o none
    Write-Host "Building WEB image in ACR ..."
    az acr build -r $ACR -g $RG -t "legalrent-web:$IMAGE_TAG" -f docker/frontend/Dockerfile $ctx -o none
}

Write-Host "Ensuring Container Apps environment $CAE ..."
$prevEa = $ErrorActionPreference
$ErrorActionPreference = "Continue"
az extension add --name containerapp -y 2>&1 | Out-Null
az provider register --namespace Microsoft.App --wait -o none 2>&1 | Out-Null
$ErrorActionPreference = $prevEa

if (-not (Test-AzCommand { az containerapp env show -g $RG -n $CAE -o none })) {
    az containerapp env create -g $RG -n $CAE -l $LOC -o none
}

$apiImage = "$acrLoginServer/legalrent-api:$IMAGE_TAG"
$webImage = "$acrLoginServer/legalrent-web:$IMAGE_TAG"

function Get-ContainerAppFqdn {
    param([string]$Name)
    az containerapp show -g $RG -n $Name --query "properties.configuration.ingress.fqdn" -o tsv
}

function Ensure-ContainerApp {
    param(
        [string]$Name,
        [string]$Image,
        [int]$TargetPort,
        [string[]]$EnvVars
    )
    $ingress = "external"
    if (-not (Test-AzCommand { az containerapp show -g $RG -n $Name -o none })) {
        az containerapp create -g $RG -n $Name --environment $CAE `
            --image $Image `
            --registry-server $acrLoginServer `
            --registry-username $acrUser `
            --registry-password $acrPass `
            --target-port $TargetPort `
            --ingress $ingress `
            --cpu 1.0 --memory 2.0Gi `
            --env-vars @EnvVars -o none
    } else {
        az containerapp update -g $RG -n $Name `
            --image $Image `
            --set-env-vars @EnvVars -o none
    }
}

# Placeholder URLs; updated after FQDNs are known.
$apiUrlPlaceholder = "https://placeholder-api"
$webUrlPlaceholder = "https://placeholder-web"

$localEnv = Read-DotEnvFile (Join-Path $Root ".env")
$azureLocal = Read-DotEnvFile (Join-Path $SecretsDir "azure.local.env")
$merged = Merge-EnvMaps @($localEnv, $azureLocal)

$sqlHost = "$SQL_SERVER.database.windows.net"
$secretKey = if ($merged["SECRET_KEY"]) { $merged["SECRET_KEY"] } else { "change-me-run-deploy-with-local-env" }
$openAiKey = $merged["OPENAI_API_KEY"]
$llmProvider = if ($merged["LLM_PROVIDER"]) { $merged["LLM_PROVIDER"] } else { "openai" }

function Format-ContainerAppEnv {
    param([hashtable]$Map)
    $list = New-Object System.Collections.Generic.List[string]
    foreach ($k in $Map.Keys) {
        $v = [string]$Map[$k]
        if ($null -eq $v) { $v = "" }
        $list.Add("${k}=$v")
    }
    return $list.ToArray()
}

$apiEnv = Format-ContainerAppEnv @{
    DB_SERVER                             = $sqlHost
    DB_NAME                               = $SQL_DB
    DB_USER                               = $SQL_ADMIN
    DB_PASSWORD                           = $sqlPassword
    DB_DRIVER                             = "ODBC Driver 18 for SQL Server"
    DB_TRUSTED_CONNECTION                 = "false"
    SECRET_KEY                            = $secretKey
    LLM_PROVIDER                          = $llmProvider
    OPENAI_API_KEY                        = $openAiKey
    OPENAI_MODEL                          = if ($merged["OPENAI_MODEL"]) { $merged["OPENAI_MODEL"] } else { "gpt-4o-mini" }
    FRONTEND_BASE_URL                     = $webUrlPlaceholder
    APP_BASE_URL                          = $apiUrlPlaceholder
    LEGAL_CAG_ENABLED                     = "true"
    LEGAL_CAG_CORPUS_PATH                 = "docs/legal-sources/cag-corpus-v1.md"
    GUARDRAILS_ENABLED                    = "true"
    OCR_ENABLED                           = "false"
    NOTIFICATION_DEV_MODE                 = if ($merged["NOTIFICATION_DEV_MODE"]) { $merged["NOTIFICATION_DEV_MODE"] } else { "false" }
    AZURE_COMMUNICATION_CONNECTION_STRING = $merged["AZURE_COMMUNICATION_CONNECTION_STRING"]
    AZURE_COMMUNICATION_SENDER_ADDRESS    = $merged["AZURE_COMMUNICATION_SENDER_ADDRESS"]
    # Ingress terminates TLS; avoid redirect loops until X-Forwarded-Proto is honored in the image.
    FORCE_HTTPS                           = "false"
}

Ensure-ContainerApp -Name $API_APP -Image $apiImage -TargetPort 8000 -EnvVars $apiEnv
Ensure-ContainerApp -Name $WEB_APP -Image $webImage -TargetPort 80 -EnvVars @(
    "API_BACKEND_URL=$apiUrlPlaceholder"
)

$apiFqdn = Get-ContainerAppFqdn -Name $API_APP
$webFqdn = Get-ContainerAppFqdn -Name $WEB_APP
$apiUrl = "https://$apiFqdn"
$webUrl = "https://$webFqdn"

az containerapp update -g $RG -n $API_APP --set-env-vars `
    "FRONTEND_BASE_URL=$webUrl" "APP_BASE_URL=$apiUrl" -o none | Out-Null
az containerapp update -g $RG -n $WEB_APP --set-env-vars `
    "API_BACKEND_URL=$apiUrl" "API_BACKEND_HOST=$apiFqdn" -o none | Out-Null

if (-not $SkipDbInit) {
    $sqlEndpoint = "$SQL_SERVER.database.windows.net"
    $sqlcmd = Get-Command sqlcmd -ErrorAction SilentlyContinue
    if (-not $sqlcmd) {
        Write-Warning "sqlcmd not found; skip DB init or install SQL tools and re-run without -SkipDbInit"
    } else {
        Write-Host "Initializing Azure SQL schema ..."
        $scriptsDir = Join-Path $Root "docs\database"
        $migrationsDir = Join-Path $scriptsDir "migrations"
        $common = @("-S", $sqlEndpoint, "-U", $SQL_ADMIN, "-P", $sqlPassword, "-C", "-b")
        # Database already created via `az sql db create`; run DDL/seed only.
        & sqlcmd @common -d $SQL_DB -i (Join-Path $scriptsDir "ddl.sql")
        & sqlcmd @common -d $SQL_DB -i (Join-Path $scriptsDir "seed.sql")
        Push-Location $migrationsDir
        try {
            & sqlcmd @common -d $SQL_DB -i "run-all-incremental.sql"
        } finally { Pop-Location }
        & sqlcmd @common -d $SQL_DB -i (Join-Path $migrationsDir "12-migrate-remove-administrator.sql")
        Write-Host "Database initialization complete."
    }
}

