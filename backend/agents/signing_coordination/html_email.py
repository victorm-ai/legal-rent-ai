"""HTML email body for signing coordination."""

from __future__ import annotations

import html
from typing import Any

SIGNING_PROCESS_MESSAGE = (
    "Your file was closed on the platform. Review the comparison between the original contract "
    "and the approved edited version. Then use the secure link to choose the date and time for "
    "in-person signing with your lawyer (and coordination with the landlord). "
    "Online booking is indicative; your lawyer will confirm the appointment."
)


def build_comparison_table_html(comparison: dict[str, Any]) -> str:
    rows = comparison.get("rows") or []
    if not rows:
        changes = comparison.get("changes") or []
        if changes:
            header = (
                "<tr><th>Type</th><th>Category</th><th>Previous value</th>"
                "<th>New value</th><th>Description</th></tr>"
            )
            body_rows = []
            for change in changes:
                body_rows.append(
                    "<tr>"
                    f"<td>{html.escape(str(change.get('change_type') or ''))}</td>"
                    f"<td>{html.escape(str(change.get('category') or ''))}</td>"
                    f"<td>{html.escape(str(change.get('old_value') or ''))}</td>"
                    f"<td>{html.escape(str(change.get('new_value') or ''))}</td>"
                    f"<td>{html.escape(str(change.get('description') or ''))}</td>"
                    "</tr>"
                )
            return (
                "<table border=\"1\" cellpadding=\"6\" cellspacing=\"0\" "
                "style=\"border-collapse:collapse;width:100%\">"
                f"{header}{''.join(body_rows)}</table>"
            )
        return "<p><em>No comparison rows on record.</em></p>"

    header = (
        "<tr><th>Item</th><th>Type</th><th>Original</th>"
        "<th>Edited</th><th>Difference</th></tr>"
    )
    body_rows = []
    for row in rows:
        body_rows.append(
            "<tr>"
            f"<td>{html.escape(str(row.get('item_key') or ''))}</td>"
            f"<td>{html.escape(str(row.get('item_type') or ''))}</td>"
            f"<td>{html.escape(str(row.get('original_value') or ''))}</td>"
            f"<td>{html.escape(str(row.get('new_value') or ''))}</td>"
            f"<td>{html.escape(str(row.get('difference') or row.get('change_type') or ''))}</td>"
            "</tr>"
        )
    return (
        "<table border=\"1\" cellpadding=\"6\" cellspacing=\"0\" "
        "style=\"border-collapse:collapse;width:100%\">"
        f"{header}{''.join(body_rows)}</table>"
    )


def build_signing_coordination_html(
    *,
    contract_title: str | None,
    narrative_summary: str,
    comparison: dict[str, Any],
    schedule_url: str,
    closure_notes: str,
    process_message: str | None = None,
) -> str:
    title = html.escape(contract_title or "Lease contract")
    narrative = html.escape(narrative_summary).replace("\n", "<br/>")
    notes = html.escape(closure_notes).replace("\n", "<br/>")
    process_text = html.escape(process_message or SIGNING_PROCESS_MESSAGE)
    table = build_comparison_table_html(comparison)
    link = html.escape(schedule_url)

    return f"""<!DOCTYPE html>
<html lang="en">
<body style="font-family:Segoe UI,Arial,sans-serif;color:#111;line-height:1.5;max-width:720px">
  <h2>Signing coordination — {title}</h2>
  <p>{narrative}</p>
  <h3>Next steps</h3>
  <p>{process_text}</p>
  <h3>Lawyer closing notes</h3>
  <p>{notes}</p>
  <h3>Final comparison (original vs edited version)</h3>
  {table}
  <h3>In-person signing</h3>
  <p>Select date and time using the secure link (calendar for the next 30 business days, 09:00–18:00 CDMX):</p>
  <p><a href="{link}" style="font-weight:600">Schedule in-person signing</a></p>
  <p style="word-break:break-all;font-size:13px;color:#444">{link}</p>
  <p style="color:#555;font-size:12px">Message generated by Legal Rent AI. Formal signing takes place outside the system.</p>
</body>
</html>"""
